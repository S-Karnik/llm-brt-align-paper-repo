import os
import torch
import argparse
import numpy as np
from tqdm import tqdm
import sys

# Ensure project root is in path
sys.path.append(os.path.abspath(os.path.join(os.path.dirname(__file__), '../')))
import directories

def stack_original_shards(base_path, split, num_shards):
    """
    Stacks shards of embeddings, masks, labels, etc. generated by the finetune data collection script.
    """
    keys = ["embeddings", "masks", "labels", "prompts", "responses"]
    stacked = {k: [] for k in keys}
    
    print(f"Stacking original data shards from {base_path}...")
    for shard_id in tqdm(range(num_shards), desc="Original Shards"):
        for k in keys:
            path = os.path.join(base_path, f"{split}_{k}_shard{shard_id}.pt")
            if not os.path.exists(path):
                # Check for "is_safes" if "labels" is missing
                if k == "labels":
                    alt_path = os.path.join(base_path, f"{split}_is_safes_shard{shard_id}.pt")
                    if os.path.exists(alt_path):
                        path = alt_path
                    else:
                        continue
                else:
                    continue
            
            data = torch.load(path, weights_only=False)
            if isinstance(data, list):
                stacked[k].extend(data)
            elif torch.is_tensor(data):
                # If it's a single tensor (e.g. embeddings stacked in shard), 
                # we usually want to keep them as a list of tensors for variable length compatibility
                if data.dim() > 1 and k == "embeddings":
                    stacked[k].extend([t for t in data])
                else:
                    stacked[k].append(data)
            else:
                stacked[k].append(data)
                
    return stacked

def stack_classifier_shards(save_dir, split, num_shards):
    """
    Stacks shards generated by evaluate_ground_truth_classifier_with_sharding.py.
    """
    keys = ["prefix_scores", "final_scores", "unsafe_indices"]
    stacked = {k: [] for k in keys}
    
    print(f"Stacking classifier shards from {save_dir}...")
    for shard_idx in tqdm(range(num_shards), desc="Classifier Shards"):
        # Format: {split}_shard{shard}of{S}
        tag = f"{split}_shard{shard_idx}of{num_shards}"
        
        for k in keys:
            path = os.path.join(save_dir, f"{tag}_{k}.pt")
            if not os.path.exists(path):
                continue
            
            data = torch.load(path, weights_only=False)
            if isinstance(data, list):
                stacked[k].extend(data)
            elif isinstance(data, np.ndarray):
                stacked[k].extend(data.tolist())
            elif torch.is_tensor(data):
                stacked[k].extend(data.tolist())
            else:
                stacked[k].append(data)
                
    return stacked

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--model_name", type=str, required=True)
    parser.add_argument("--dataset_name", type=str, required=True, choices=["beavertails", "real_toxicity", "ultrasafety"])
    parser.add_argument("--split", type=str, required=True)
    parser.add_argument("--num_shards", type=int, required=True)
    parser.add_argument("--skip_original", action="store_true", help="Skip stacking original data")
    parser.add_argument("--skip_classifier", action="store_true", help="Skip stacking classifier outputs")
    parser.add_argument("--use_layer_dir", action="store_true", help="Use layer-specific embeddings")
    parser.add_argument("--layer_idx", type=int, default=20, help="Layer index to use for embeddings")

    args = parser.parse_args()
    
    model_tag = args.model_name.replace("/", "_")
    
    # Destination directory where training scripts expect data
    # f'{args.data_dir}/{args.dataset_name}/{args.model_name.replace("/", "_")}/{split}'
    layer_suffix = f"_layer_{args.layer_idx}" if args.use_layer_dir else ""
    dest_dir = os.path.join(directories.DATA_CACHE_DIR, f"{args.dataset_name}_llm_generated{layer_suffix}", model_tag)
    os.makedirs(dest_dir, exist_ok=True)
    
    # Source directory for original shards (often in *_llm_generated)
    source_data_dir = os.path.join(directories.DATA_CACHE_DIR, f"{args.dataset_name}_llm_generated{layer_suffix}", model_tag)
    if not os.path.exists(source_data_dir):
        source_data_dir = dest_dir

    # Source directory for classifier shards
    classifier_shard_dir = os.path.join(directories.GROUND_TRUTH_PER_TOKEN_LABELS_DIR, args.dataset_name, model_tag)

    # 1. Handle original shards
    if not args.skip_original:
        orig_stacked = stack_original_shards(source_data_dir, args.split, args.num_shards)
        for k, data in orig_stacked.items():
            if not data:
                continue
            
            # Map "labels" to "is_safes" for training script compatibility
            save_name = k if k != "labels" else "is_safes"
            save_path = os.path.join(dest_dir, f"{args.split}_{save_name}.pt")
            torch.save(data, save_path)
            print(f"  - Saved {len(data)} items to {save_path}")

    # 2. Handle classifier shards
    if not args.skip_classifier:
        clf_stacked = stack_classifier_shards(classifier_shard_dir, args.split, args.num_shards)
        
        # Save prefix_scores
        if clf_stacked["prefix_scores"]:
            prefix_save_path = os.path.join(dest_dir, f"{args.split}_prefix_scores.pt")
            torch.save(clf_stacked["prefix_scores"], prefix_save_path)
            print(f"  - Saved {len(clf_stacked['prefix_scores'])} prefix_scores to {prefix_save_path}")
            
        # Save final_scores AND alias "scores"
        if clf_stacked["final_scores"]:
            final_scores = clf_stacked["final_scores"]
            final_save_path = os.path.join(dest_dir, f"{args.split}_final_scores.pt")
            scores_save_path = os.path.join(dest_dir, f"{args.split}_scores.pt")
            torch.save(final_scores, final_save_path)
            torch.save(final_scores, scores_save_path)
            print(f"  - Saved {len(final_scores)} final_scores to {final_save_path} and {scores_save_path}")
            
        # Save unsafe_indices
        if clf_stacked["unsafe_indices"]:
            indices = np.array(clf_stacked["unsafe_indices"])
            unsafe_save_path = os.path.join(dest_dir, f"{args.split}_unsafe_indices.pt")
            torch.save(indices, unsafe_save_path)
            print(f"  - Saved {len(indices)} unsafe_indices to {unsafe_save_path}")

    print("\nStacking complete.")

if __name__ == "__main__":
    main()
